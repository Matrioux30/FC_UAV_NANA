import os
import numpy as np
import mpc_model as m

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'include', 'mpc_constants.h')


def c_array(name, dims, mat, indent=''):
    mat = np.atleast_2d(mat)
    rows = ',\n'.join(f'{indent}    {{' + ', '.join(f'{v:.16e}' for v in row) + '}' for row in mat)
    return f'{indent}inline const double {name}{dims} = {{\n{rows}\n{indent}}};\n'


def c_vector(name, dims, vec, indent=''):
    return f'{indent}inline const double {name}{dims} = {{' + ', '.join(f'{v:.16e}' for v in vec) + '};\n'


def coef_frac_bits(*arrays):
    """Fractional bits of a signed 32-bit coefficient format holding max|a| with one bit of headroom."""
    peak = max(np.abs(np.asarray(a)).max() for a in arrays)
    int_bits = int(np.floor(np.log2(peak))) + 2
    return 32 - max(int_bits, 1)


def format_block(fmt):
    sc = m.FORMAT_SCALING[fmt]
    p = m.build_scaled_problem(**sc)
    x_scale, r_scale = m.input_scales(fmt)
    mx = p['Mxs'] / x_scale[None, :]
    mr = p['Mrs'] / r_scale[None, :]
    fw, fmx, fmr = coef_frac_bits(p['W']), coef_frac_bits(mx), coef_frac_bits(mr)
    fp = coef_frac_bits([p['rho'], m.ALPHA, 1.0 - m.ALPHA])
    ind = '    '
    return ''.join([
        f'// {fmt}: VAR_SCALE = {sc["var_scale"]:g}, COST_SCALE = {sc["cost_scale"]:g}, cond(H) = {np.linalg.cond(p["Hs"]):.1f}\n',
        f'// Inputs are pre-multiplied: x_q = X_SCALE .* x, r_q = R_SCALE .* r (powers of two), MX/MR already divided.\n',
        f'// Coefficient ROM formats (signed 32-bit): W Q{32-fw}.{fw}, MX Q{32-fmx}.{fmx}, MR Q{32-fmr}.{fmr}, '
        f'rho/alpha Q{32-fp}.{fp}\n',
        f'namespace qp_{fmt} {{\n',
        f'{ind}constexpr double RHO = {p["rho"]!r};\n',
        f'{ind}constexpr int W_FRAC = {fw};\n{ind}constexpr int MX_FRAC = {fmx};\n',
        f'{ind}constexpr int MR_FRAC = {fmr};\n{ind}constexpr int P_FRAC = {fp};\n',
        c_array('H_MAT', '[NU_TOTAL][NU_TOTAL]', p['Hs'], ind),
        c_array('W_MAT', '[NU_TOTAL][NU_TOTAL]', p['W'], ind),
        c_array('MX_MAT', '[NU_TOTAL][NX]', mx, ind),
        c_array('MR_MAT', '[NU_TOTAL][NR]', mr, ind),
        c_vector('X_SCALE', '[NX]', x_scale, ind),
        c_vector('R_SCALE', '[NR]', r_scale, ind),
        c_vector('U_SCALE', '[NU_TOTAL]', p['E'], ind),
        c_vector('Z_MIN', '[NU_TOTAL]', p['z_min'], ind),
        c_vector('Z_MAX', '[NU_TOTAL]', p['z_max'], ind),
        f'}} // namespace qp_{fmt}\n',
        f'inline const QpConstants QP_{fmt.upper()} = {{qp_{fmt}::RHO, qp_{fmt}::W_MAT, qp_{fmt}::MX_MAT, '
        f'qp_{fmt}::MR_MAT, qp_{fmt}::X_SCALE, qp_{fmt}::R_SCALE, qp_{fmt}::U_SCALE, qp_{fmt}::Z_MIN, qp_{fmt}::Z_MAX}};\n\n',
    ])


def main():
    p = m.build_scaled_problem()
    fmt = lambda a: ', '.join(f'{v:g}' for v in a)
    parts = [
        '// Auto-generated by scripts/generate_mpc_constants.py -- do not edit by hand.\n',
        f'// Q = diag({fmt(m.Q_DIAG)}), R = diag({fmt(m.R_DIAG)})\n',
        '// Scaled QP solved online: min 0.5 z\'Hz + g\'z, Z_MIN <= z <= Z_MAX, U = U_SCALE .* z,\n',
        '//   g = MX_MAT * x - MR_MAT * r,  r = [x_ref, y_ref, z_ref, psi_ref] for p = 0..NP-1 (NR values).\n',
        '// Each number format has its own range scaling (same solution, different magnitudes).\n',
        '#ifndef MPC_CONSTANTS_H\n#define MPC_CONSTANTS_H\n\n',
        f'constexpr int NX = {m.NX};\nconstexpr int NU = {m.NU};\nconstexpr int NP = {m.NP};\nconstexpr int NC = {m.NC};\n',
        f'constexpr int NU_TOTAL = {m.NU_TOTAL};\nconstexpr int NREF = {len(m.REF_CHANNELS)};\nconstexpr int NR = NREF * NP;\n',
        f'constexpr double TS = {m.TS};\n',
        f'constexpr double RHO_UNIT = {m.RHO!r};\nconstexpr double ALPHA = {m.ALPHA!r};\nconstexpr int N_ITER = {m.N_ITER};\n\n',
        c_vector('U_MAX_CH', '[NU]', m.U_MAX_CH), '\n',
        c_array('AD', '[NX][NX]', p['Ad']), '\n',
        c_array('BD', '[NX][NU]', p['Bd']), '\n',
        'struct QpConstants {\n    double rho;\n    const double (*W)[NU_TOTAL];\n    const double (*MX)[NX];\n'
        '    const double (*MR)[NR];\n    const double* x_scale;\n    const double* r_scale;\n    const double* u_scale;\n    const double* z_min;\n    const double* z_max;\n};\n\n',
    ]
    parts += [format_block(f) for f in m.FORMAT_SCALING]
    parts.append(f'// Deployed format; the double reference uses the same constants.\n'
                 f'inline const QpConstants& QP_DEPLOYED = QP_{m.DEPLOYED_FORMAT.upper()};\n\n')
    parts.append('#endif // MPC_CONSTANTS_H\n')
    with open(OUT, 'w', newline='\n') as f:
        f.write(''.join(parts))
    print(f'Wrote {os.path.normpath(OUT)}')


if __name__ == '__main__':
    main()
