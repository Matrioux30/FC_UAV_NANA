"""Converts the golden-model export (quadcopter_mpc/test_vectors) into files the RTL and testbench use.

Per format (q16_16, q8_24) writes mpc_accel_hw/mem/<fmt>/:
  coef_col.mem  112 lines x 640 bit. Address a holds column a of [MX | MR | W] for all 20 lanes
                (lane 19 in the most significant word): a = 0..11 MX, 12..91 MR, 92..111 W.
  zmin.mem, zmax.mem, params.mem (rho, alpha, 1-alpha)   copied as-is
  config.vh, config.tcl   fractional bits of each coefficient ROM (RTL parameters)
  tv.hex        one test vector per line: 92 inputs (x0..x11, r0..r79), 20 expected g, 20 expected z (hex)
Standard library only. Run: python scripts/gen_hw_files.py
"""
import csv
import os
import re

NX, NR, NL = 12, 80, 20
HERE = os.path.dirname(os.path.abspath(__file__))
HW = os.path.normpath(os.path.join(HERE, '..'))
SRC = os.path.normpath(os.path.join(HW, '..', 'quadcopter_mpc', 'test_vectors'))


def read_mem(path):
    return [line.strip() for line in open(path) if line.strip()]


def h32(v):
    return f'{int(v) & 0xFFFFFFFF:08X}'


def gen(fmt):
    rom = os.path.join(SRC, f'rom_{fmt}')
    out = os.path.join(HW, 'mem', fmt)
    os.makedirs(out, exist_ok=True)

    w, mx, mr = (read_mem(os.path.join(rom, f'{k}.mem')) for k in ('W', 'MX', 'MR'))
    assert len(w) == NL * NL and len(mx) == NL * NX and len(mr) == NL * NR
    cols = [[mx[i * NX + j] for i in range(NL)] for j in range(NX)]
    cols += [[mr[i * NR + j] for i in range(NL)] for j in range(NR)]
    cols += [[w[i * NL + j] for i in range(NL)] for j in range(NL)]
    with open(os.path.join(out, 'coef_col.mem'), 'w') as f:
        for c in cols:
            f.write(''.join(reversed(c)) + '\n')

    for src, dst in (('ZMIN', 'zmin'), ('ZMAX', 'zmax'), ('PARAMS_rho_alpha_1malpha', 'params')):
        with open(os.path.join(out, f'{dst}.mem'), 'w') as f:
            f.write('\n'.join(read_mem(os.path.join(rom, f'{src}.mem'))) + '\n')

    text = open(os.path.join(rom, 'formats.txt')).read()
    frac = {k: int(re.search(rf'^{k}\s+Q\d+\.(\d+)', text, re.M).group(1))
            for k in ('data', 'W', 'MX', 'MR', 'PARAMS')}
    n_iter = int(re.search(r'^N_ITER\s+(\d+)', text, re.M).group(1))
    names = {'W': 'FRAC_W', 'MX': 'FRAC_MX', 'MR': 'FRAC_MR', 'PARAMS': 'FRAC_P', 'data': 'FRAC_DATA'}
    with open(os.path.join(out, 'config.vh'), 'w') as f:
        f.write(f'// Generated by gen_hw_files.py from rom_{fmt}/formats.txt\n')
        for k, n in names.items():
            f.write(f'`define {n} {frac[k]}\n')
        f.write(f'`define N_ITER_DEFAULT {n_iter}\n')
    with open(os.path.join(out, 'config.tcl'), 'w') as f:
        f.write(f'# Generated by gen_hw_files.py from rom_{fmt}/formats.txt\n')
        for k, n in names.items():
            f.write(f'set {n} {frac[k]}\n')
        f.write(f'set N_ITER_DEFAULT {n_iter}\n')

    n = 0
    with open(os.path.join(SRC, f'test_vectors_{fmt}.csv'), newline='') as fin, \
            open(os.path.join(out, 'tv.hex'), 'w') as fout:
        rd = csv.DictReader(fin)
        rcols = [c for c in rd.fieldnames if re.fullmatch(r'r\d+_[xyzw]', c)]
        assert len(rcols) == NR
        for row in rd:
            vals = [row[f'x{i}'] for i in range(NX)] + [row[c] for c in rcols]
            vals += [row[f'g{i}'] for i in range(NL)] + [row[f'z{i}'] for i in range(NL)]
            fout.write(' '.join(h32(v) for v in vals) + '\n')
            n += 1
    print(f'{fmt}: {len(cols)} kolom ROM, {n} test vector, frac {frac}, N_ITER {n_iter} -> {out}')

    def floats(key):
        return re.search(rf'^{key}\s+([^\(\n]+)', text, re.M).group(1).split()
    return (f'    {{"{fmt}", {frac["data"]}, {frac["W"]}, {frac["MX"]}, {frac["MR"]}, {frac["PARAMS"]}, {n_iter},\n'
            f'     {{{", ".join(floats("X_SCALE"))}}},\n'
            f'     {{{", ".join(floats("R_SCALE"))}}},\n'
            f'     {{{", ".join(floats("U_SCALE"))}}}}},\n')


def write_sw_header(entries):
    path = os.path.join(HW, 'deploy', 'sw', 'mpc_formats.h')
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w') as f:
        f.write('// Generated by scripts/gen_hw_files.py from quadcopter_mpc/test_vectors/rom_*/formats.txt\n'
                '#pragma once\n\n'
                'struct MpcFormat {\n'
                '    const char* name;\n'
                '    int frac_data, frac_w, frac_mx, frac_mr, frac_p, n_iter;\n'
                '    double x_scale[12];\n'
                '    double r_scale[4];   // x_ref, y_ref, z_ref, psi_ref (repeated for every horizon step)\n'
                '    double u_scale[4];   // u_k = u_scale[k] * z_k, F_total += HOVER_THRUST\n'
                '};\n\n'
                'constexpr double HOVER_THRUST = 0.068 * 9.81;   // MASS * GRAVITY [N]\n\n'
                'inline const MpcFormat MPC_FORMATS[] = {\n' + ''.join(entries) + '};\n')
    print(f'-> {path}')


if __name__ == '__main__':
    write_sw_header([gen(fmt) for fmt in ('q16_16', 'q8_24')])
